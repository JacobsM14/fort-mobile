export type ExerciseKey = (typeof EXERCISE_CATALOG)[number]["key"];

const EXERCISE_KEYS = new Set<string>(EXERCISE_CATALOG.map((e) => e.key));

// La BD puede tener una key que ya no está en el catálogo (se quitó en una
// versión nueva de la app pero sigue en el historial).
export function isExerciseKey(key: string | null): key is ExerciseKey {
  return key !== null && EXERCISE_KEYS.has(key);
}

export function getExerciseText(
  exercise: {
    key: string | null;
    name: string | null;
    description: string | null;
  },
  t: Translations,
) {
  const catalog = isExerciseKey(exercise.key)
    ? t.exerciseCatalog[exercise.key]
    : undefined;

  return {
    name: exercise.name ?? catalog?.name ?? exercise.key ?? "",
    description: exercise.description ?? catalog?.description ?? null,
  };
}
