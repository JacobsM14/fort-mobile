// Writes src/features/exercises/images.ts from the files in assets/exercises
// (<exercise key>_<n>.webp). Metro only bundles images passed to a literal
// require(), so the map can't be built at runtime from the key.
// Run it after adding or removing images: npm run images
import { readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const imagesDir = path.join(root, "assets/exercises");
const outFile = path.join(root, "src/features/exercises/images.ts");
const IMAGE_NAME = /^([a-z0-9_]+)_(\d+)\.webp$/;

const imagesByKey = new Map();
for (const file of readdirSync(imagesDir)) {
  const match = IMAGE_NAME.exec(file);
  if (match === null) {
    continue;
  }
  const [, key, index] = match;
  const images = imagesByKey.get(key) ?? [];
  images.push({ file, index: Number(index) });
  imagesByKey.set(key, images);
}

const entries = [...imagesByKey.keys()].sort().map((key) => {
  const requires = imagesByKey
    .get(key)
    .sort((a, b) => a.index - b.index)
    .map(({ file }) => `    require("../../../assets/exercises/${file}"),`)
    .join("\n");
  return `  ${key}: [\n${requires}\n  ],`;
});

const source = `// Generated by scripts/generate-exercise-images.mjs. Don't edit it by hand:
// run \`npm run images\` after adding or removing files in assets/exercises.
import type { ExerciseKey } from "./catalog";

export const EXERCISE_IMAGES: Partial<Record<ExerciseKey, readonly number[]>> = {
${entries.join("\n")}
};
`;

writeFileSync(outFile, source);
console.log(`${imagesByKey.size} exercises with images -> ${path.relative(root, outFile)}`);
