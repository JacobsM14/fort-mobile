// Writes src/features/body/bmi-for-age.ts from the WHO 2007 BMI-for-age
// expanded tables (5 to 19 years, by month), downloaded from the WHO site.
// The tables don't change: run it again only if a link breaks or to check the
// data: node scripts/generate-bmi-for-age.mjs
import { Buffer } from "node:buffer";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { inflateRawSync } from "node:zlib";

const root = path.resolve(import.meta.dirname, "..");
const outFile = path.join(root, "src/features/body/bmi-for-age.ts");

// From https://www.who.int/tools/growth-reference-data-for-5to19-years/indicators/bmi-for-age
// ("Expanded tables for constructing national health cards", z-scores).
const BASE =
  "https://cdn.who.int/media/docs/default-source/child-growth/growth-reference-5-19-years/bmi-for-age-(5-19-years)";
const SOURCES = {
  male: `${BASE}/bmi-boys-z-who-2007-exp.xlsx?sfvrsn=a84bca93_2`,
  female: `${BASE}/bmi-girls-z-who-2007-exp.xlsx?sfvrsn=79222875_2`,
};
const FIRST_MONTH = 61;
const LAST_MONTH = 228;

// An .xlsx is a zip of XML files. Node has no zip reader, so this walks the
// central directory and inflates the one entry asked for.
function readZipEntry(zip, name) {
  const endOfDirectory = zip.lastIndexOf(Buffer.from([0x50, 0x4b, 0x05, 0x06]));
  const entries = zip.readUInt16LE(endOfDirectory + 10);
  let offset = zip.readUInt32LE(endOfDirectory + 16);
  for (let i = 0; i < entries; i++) {
    const method = zip.readUInt16LE(offset + 10);
    const size = zip.readUInt32LE(offset + 20);
    const nameLength = zip.readUInt16LE(offset + 28);
    const extraLength = zip.readUInt16LE(offset + 30);
    const commentLength = zip.readUInt16LE(offset + 32);
    const localHeader = zip.readUInt32LE(offset + 42);
    const entryName = zip.toString(
      "utf8",
      offset + 46,
      offset + 46 + nameLength,
    );
    if (entryName === name) {
      const dataStart =
        localHeader +
        30 +
        zip.readUInt16LE(localHeader + 26) +
        zip.readUInt16LE(localHeader + 28);
      const data = zip.subarray(dataStart, dataStart + size);
      return (method === 0 ? data : inflateRawSync(data)).toString("utf8");
    }
    offset += 46 + nameLength + extraLength + commentLength;
  }
  throw new Error(`${name} not found in the workbook`);
}

// The sheet's rows as { header: value } objects, the first row being the header.
function readSheet(xlsx) {
  const strings = [
    ...readZipEntry(xlsx, "xl/sharedStrings.xml").matchAll(
      /<si>.*?<t[^>]*>(.*?)<\/t>.*?<\/si>/gs,
    ),
  ].map((match) => match[1]);
  const rows = [
    ...readZipEntry(xlsx, "xl/worksheets/sheet1.xml").matchAll(
      /<row[^>]*>(.*?)<\/row>/gs,
    ),
  ].map((row) =>
    [
      ...row[1].matchAll(
        /<c r="([A-Z]+)\d+"([^>]*?)(?:\/>|>(?:<v>(.*?)<\/v>)?<\/c>)/g,
      ),
    ].map(([, column, attributes, value]) => ({
      column,
      value: attributes.includes('t="s"') ? strings[Number(value)] : value,
    })),
  );
  const [header, ...body] = rows;
  const names = new Map(header.map((cell) => [cell.column, cell.value]));
  return body.map((cells) =>
    Object.fromEntries(
      cells.map((cell) => [names.get(cell.column), cell.value]),
    ),
  );
}

async function loadTable(url) {
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`${response.status} downloading ${url}`);
  }
  const rows = readSheet(Buffer.from(await response.arrayBuffer())).map(
    (row) => ({
      month: Number(row.Month),
      l: Number(row.L),
      m: Number(row.M),
      s: Number(row.S),
    }),
  );
  // Every month in order, none missing: the lookup goes by position.
  rows.forEach((row, index) => {
    if (
      row.month !== FIRST_MONTH + index ||
      [row.l, row.m, row.s].some(Number.isNaN)
    ) {
      throw new Error(`Unexpected row ${index + 2} in ${url}`);
    }
  });
  if (rows.length !== LAST_MONTH - FIRST_MONTH + 1) {
    throw new Error(
      `Expected months ${FIRST_MONTH} to ${LAST_MONTH} in ${url}`,
    );
  }
  return rows;
}

const tables = {
  male: await loadTable(SOURCES.male),
  female: await loadTable(SOURCES.female),
};

const lines = (rows) =>
  rows
    .map(
      ({ month, l, m, s }) =>
        `    { month: ${month}, l: ${l}, m: ${m}, s: ${s} },`,
    )
    .join("\n");

const source = `// Generated by scripts/generate-bmi-for-age.mjs. Don't edit it by hand:
// run \`node scripts/generate-bmi-for-age.mjs\` to download it again.
// WHO 2007 BMI-for-age reference, 5 to 19 years, one row per completed month.
// Source: https://www.who.int/tools/growth-reference-data-for-5to19-years
import type { Gender } from "@/constants/enums";

// The reference is by sex, so only these two have one.
export type ReferenceSex = Extract<Gender, "female" | "male">;

export type LmsRow = { month: number; l: number; m: number; s: number };

export const BMI_FOR_AGE_FIRST_MONTH = ${FIRST_MONTH};
export const BMI_FOR_AGE_LAST_MONTH = ${LAST_MONTH};

// Row i is month BMI_FOR_AGE_FIRST_MONTH + i.
export const BMI_FOR_AGE: Record<ReferenceSex, readonly LmsRow[]> = {
  male: [
${lines(tables.male)}
  ],
  female: [
${lines(tables.female)}
  ],
};
`;

writeFileSync(outFile, source);
console.log(
  `${tables.male.length} months per sex -> ${path.relative(root, outFile)}`,
);
